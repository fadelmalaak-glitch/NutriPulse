/**
 * Represents whether the user initiated an explicit Sign Up or Log In flow.
 */
enum class AuthMode {
    LOG_IN,
    SIGN_UP
}

/**
 * Initial onboarding preferences optionally selected during Sign Up before Google authentication.
 */
data class SignUpPreferences(
    val goalType: String = "lose",
    val dietaryPreference: String = "High Protein",
    val activityLevel: String = "moderate"
)

/**
 * Authenticated user details returned after Firebase Google Sign-In completes.
 */
data class AuthAccountInfo(
    val uid: String,
    val displayName: String,
    val email: String?,
    val photoUrl: String?,
    val isNewUser: Boolean,
    val authMode: AuthMode
)

/**
 * Production Firebase Authentication Service using Google Sign-In with the Jetpack Credentials API.
 * Supports silent auto-sign-in, interactive Log In, interactive Sign Up with account discovery,
 * token exchange with Firebase Auth, and credential state clearing on Sign Out.
 */
class FirebaseAuthService(
    private val auth: FirebaseAuth = Firebase.auth
) {
    companion object {
        private const val TAG = "FirebaseAuthService"

        /**
         * Generates a cryptographic nonce for Google ID token requests.
         */
        fun generateNonce(byteLength: Int = 16): String {
            val bytes = ByteArray(byteLength)
            SecureRandom().nextBytes(bytes)
            return Base64.getUrlEncoder().withoutPadding().encodeToString(bytes)
        }

        /**
         * Extracts a [GoogleIdTokenCredential] from a Jetpack Credentials API [Credential] response.
         */
        fun extractGoogleIdTokenCredential(credential: Credential): GoogleIdTokenCredential? {
            if (credential is CustomCredential && credential.type == TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                return try {
                    GoogleIdTokenCredential.createFrom(credential.data)
                } catch (e: GoogleIdTokenParsingException) {
                    Log.e(TAG, "Invalid GoogleIdTokenCredential bundle", e)
                    null
                }
            }
            return null
        }

        /**
         * Converts a Google ID token string into a Firebase [AuthCredential].
         */
        fun createFirebaseGoogleCredential(idToken: String): AuthCredential {
            require(idToken.isNotBlank()) { "Google ID token must not be blank" }
            return GoogleAuthProvider.getCredential(idToken, null)
        }
    }

    val currentUser: FirebaseUser?
        get() = auth.currentUser

    fun observeAuthState(): Flow<FirebaseUser?> = auth.authStateFlow()

    /**
     * Resolves the Web OAuth 2.0 Client ID generated by Firebase provisioning.
     */
    fun getServerClientId(context: Context): Result<String> {
        return try {
            val clientId = context.getString(R.string.default_web_client_id).trim()
            if (clientId.isBlank()) {
                Result.failure(IllegalStateException("Google Sign-In configuration missing: default_web_client_id is empty"))
            } else {
                Result.success(clientId)
            }
        } catch (e: Exception) {
            Result.failure(IllegalStateException("Google Sign-In configuration missing: default_web_client_id not found", e))
        }
    }

    /**
     * Builds a silent/auto-select [GetCredentialRequest] for returning users who have already
     * authorized their Google account with NutriPulse.
     */
    fun buildAutoSignInRequest(serverClientId: String): GetCredentialRequest {
        val googleIdOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(true)
            .setServerClientId(serverClientId)
            .setAutoSelectEnabled(true)
            .setNonce(generateNonce())
            .build()

        return GetCredentialRequest.Builder()
            .addCredentialOption(googleIdOption)
            .build()
    }

    /**
     * Builds an explicit interactive Google Sign-In request using [GetSignInWithGoogleOption].
     */
    fun buildInteractiveSignInWithGoogleRequest(serverClientId: String): GetCredentialRequest {
        val signInOption = GetSignInWithGoogleOption.Builder(serverClientId = serverClientId)
            .setNonce(generateNonce())
            .build()

        return GetCredentialRequest.Builder()
            .addCredentialOption(signInOption)
            .build()
    }

    /**
     * Builds an account-picker request that allows any Google account on the device (including new
     * accounts for Sign Up) when [GetSignInWithGoogleOption] encounters a `NoCredentialException`.
     */
    fun buildAllAccountsGoogleIdRequest(serverClientId: String): GetCredentialRequest {
        val googleIdOption = GetGoogleIdOption.Builder()
            .setFilterByAuthorizedAccounts(false)
            .setServerClientId(serverClientId)
            .setAutoSelectEnabled(false)
            .setNonce(generateNonce())
            .build()

        return GetCredentialRequest.Builder()
            .addCredentialOption(googleIdOption)
            .build()
    }

    /**
     * Attempts silent automatic login for returning users using the Credentials API.
     */
    suspend fun attemptSilentSignIn(
        context: Context,
        credentialManager: CredentialManager
    ): Result<AuthAccountInfo> {
        val existing = auth.currentUser
        if (existing != null) {
            return Result.success(existing.toAuthAccountInfo(isNewUser = false, authMode = AuthMode.LOG_IN))
        }

        val clientId = getServerClientId(context).getOrElse { return Result.failure(it) }
        val request = buildAutoSignInRequest(clientId)

        return try {
            val response = requestCredential(context, credentialManager, request)
            exchangeCredentialWithFirebase(response, AuthMode.LOG_IN)
        } catch (e: CancellationException) {
            throw e
        } catch (e: Exception) {
            Result.failure(e)
        }
    }

    /**
     * Authenticates a user interactively for either [AuthMode.SIGN_UP] or [AuthMode.LOG_IN]
     * using Google Sign-In and the Jetpack Credentials API.
     */
    suspend fun authenticateWithGoogle(
        context: Context,
        credentialManager: CredentialManager,
        authMode: AuthMode = AuthMode.LOG_IN
    ): Result<AuthAccountInfo> {
        val clientId = getServerClientId(context).getOrElse { return Result.failure(it) }
        val primaryRequest = buildInteractiveSignInWithGoogleRequest(clientId)

        return try {
            val response = try {
                requestCredential(context, credentialManager, primaryRequest)
            } catch (noCred: NoCredentialException) {
                Log.i(TAG, "No authorized credential from GetSignInWithGoogleOption; retrying with all device Google accounts", noCred)
                val fallbackRequest = buildAllAccountsGoogleIdRequest(clientId)
                requestCredential(context, credentialManager, fallbackRequest)
            }
            exchangeCredentialWithFirebase(response, authMode)
        } catch (e: CancellationException) {
            throw e
        } catch (e: GetCredentialCancellationException) {
            Result.failure(e)
        } catch (e: GetCredentialException) {
            Log.e(TAG, "CredentialManager getCredential failed (${e.type})", e)
            Result.failure(e)
        } catch (e: Exception) {
            Log.e(TAG, "Google authentication failed", e)
            Result.failure(e)
        }
    }

    private suspend fun requestCredential(
        context: Context,
        credentialManager: CredentialManager,
        request: GetCredentialRequest
    ): GetCredentialResponse {
        val activity = context as? Activity
        return if (activity != null) {
            credentialManager.getCredential(activity, request)
        } else {
            credentialManager.getCredential(context, request)
        }
    }

    private suspend fun exchangeCredentialWithFirebase(
        response: GetCredentialResponse,
        authMode: AuthMode
    ): Result<AuthAccountInfo> {
        val googleIdCredential = extractGoogleIdTokenCredential(response.credential)
            ?: return Result.failure(IllegalStateException("Unexpected credential type: ${response.credential.type}"))

        val firebaseCredential = createFirebaseGoogleCredential(googleIdCredential.idToken)
        val authResult = auth.signInWithCredential(firebaseCredential).await()
        val firebaseUser = authResult.user
            ?: return Result.failure(IllegalStateException("Firebase signInWithCredential succeeded but user is null"))

        val isNewUser = authResult.additionalUserInfo?.isNewUser == true || authMode == AuthMode.SIGN_UP
        val resolvedName = firebaseUser.displayName
            ?.takeIf { it.isNotBlank() }
            ?: googleIdCredential.displayName?.takeIf { it.isNotBlank() }
            ?: firebaseUser.email?.substringBefore("@")?.takeIf { it.isNotBlank() }
            ?: "NutriPulse Member"

        return Result.success(
            AuthAccountInfo(
                uid = firebaseUser.uid,
                displayName = resolvedName.take(100),
                email = firebaseUser.email ?: googleIdCredential.id,
                photoUrl = firebaseUser.photoUrl?.toString() ?: googleIdCredential.profilePictureUri?.toString(),
                isNewUser = isNewUser,
                authMode = authMode
            )
        )
    }

    /**
     * Signs out of Firebase Authentication and clears the Jetpack CredentialManager session state.
     */
    suspend fun signOutAndClearCredentials(credentialManager: CredentialManager) {
        auth.signOut()
        try {
            credentialManager.clearCredentialState(ClearCredentialStateRequest())
        } catch (e: ClearCredentialException) {
            Log.e(TAG, "Failed to clear credential state", e)
        } catch (e: Exception) {
            Log.e(TAG, "Unexpected error clearing credential state", e)
        }
    }

    private fun FirebaseUser.toAuthAccountInfo(
        isNewUser: Boolean,
        authMode: AuthMode
    ): AuthAccountInfo {
        val resolvedName = displayName?.takeIf { it.isNotBlank() }
            ?: email?.substringBefore("@")?.takeIf { it.isNotBlank() }
            ?: "NutriPulse Member"
        return AuthAccountInfo(
            uid = uid,
            displayName = resolvedName.take(100),
            email = email,
            photoUrl = photoUrl?.toString(),
            isNewUser = isNewUser,
            authMode = authMode
        )
    }
}

/**
 * Reactive Flow of [FirebaseUser] updates backed by [FirebaseAuth.AuthStateListener].
 */
internal fun FirebaseAuth.authStateFlow(): Flow<FirebaseUser?> = callbackFlow {
    val listener = FirebaseAuth.AuthStateListener { firebaseAuth ->
        trySend(firebaseAuth.currentUser)
    }
    addAuthStateListener(listener)
    awaitClose { removeAuthStateListener(listener) }
}

/**
 * Attempts silent auto-sign-in via Jetpack [CredentialManager] and [GetGoogleIdOption].
 */
fun attemptAutoSignIn(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onUnauthenticated: () -> Unit,
    scope: CoroutineScope,
    authService: FirebaseAuthService = FirebaseAuthService(),
    onAccountAuthenticated: (AuthAccountInfo) -> Unit = {}
) {
    scope.launch {
        val result = authService.attemptSilentSignIn(context, credentialManager)
        result.fold(
            onSuccess = { accountInfo ->
                onAccountAuthenticated(accountInfo)
                onAuthSuccess()
            },
            onFailure = {
                onUnauthenticated()
            }
        )
    }
}

/**
 * Launches the interactive Google Sign-In / Sign-Up flow via Jetpack [CredentialManager]
 * and [GetSignInWithGoogleOption].
 */
fun onGoogleSignInClicked(
    context: Context,
    credentialManager: CredentialManager,
    onAuthSuccess: () -> Unit,
    onAuthError: (String) -> Unit,
    scope: CoroutineScope,
    onAuthCancelled: () -> Unit = {},
    authMode: AuthMode = AuthMode.LOG_IN,
    authService: FirebaseAuthService = FirebaseAuthService(),
    onAccountAuthenticated: (AuthAccountInfo) -> Unit = {}
) {
    scope.launch {
        val result = authService.authenticateWithGoogle(
            context = context,
            credentialManager = credentialManager,
            authMode = authMode
        )
        result.fold(
            onSuccess = { accountInfo ->
                onAccountAuthenticated(accountInfo)
                onAuthSuccess()
            },
            onFailure = { error ->
                when (error) {
                    is GetCredentialCancellationException -> {
                        Log.w("Auth", "Google ${authMode.name} flow cancelled or dismissed: ${error.message}", error)
                        onAuthCancelled()
                    }
                    is NoCredentialException -> {
                        Log.w("Auth", "No Google credentials found on device", error)
                        onAuthError("No Google account found on this device. Please add a Google account in Android Settings and try again.")
                    }
                    else -> {
                        Log.e("Auth", "Google ${authMode.name} failed", error)
                        onAuthError(error.localizedMessage ?: "Google authentication failed. Please try again.")
                    }
                }
            }
        )
    }
}

/**
 * Signs the user out of Firebase Auth and clears the CredentialManager session state.
 */
fun signOut(
    context: Context,
    credentialManager: CredentialManager,
    onSignOutComplete: () -> Unit,
    scope: CoroutineScope,
    authService: FirebaseAuthService = FirebaseAuthService()
) {
    scope.launch {
        try {
            authService.signOutAndClearCredentials(credentialManager)
        } finally {
            onSignOutComplete()
        }
    }
}
